"use strict";
const fs = require('fs'), vm = require('vm'), assert = require('assert'), path = require('path');
const site = path.join(__dirname, 'site');
const ctx = {console}; ctx.window = ctx; ctx.globalThis = ctx; vm.createContext(ctx);
const load = (p) => vm.runInContext(fs.readFileSync(path.join(site, p), 'utf8'),ctx,{filename:p});
load('data/core.js');load('data/score_extra.js');load('data/worksheet_docs.js');
const before={};ctx.CORE.students.forEach(s=>Object.keys(ctx.CORE.ws[s]).filter(w=>w!=='WS12').forEach(w=>before[s+w]=JSON.stringify(ctx.CORE.ws[s][w])));
load('data/ws12_review.js');load('assets/ws12_review.js');load('assets/worksheet_findings.js');
const html=ctx.WorksheetFindings.page('WS12');
assert(html.includes('Revised 20261109-v2'));
assert(html.includes('Not applicable') && html.includes('Unverified') && html.includes('Blank'));
assert(html.includes('Test-error values are recorded but cannot be verified'));
assert(!html.includes('100%') && !html.includes('ROOT SPLIT VALID'));
assert(html.includes('Item 15') && html.includes('Item 10'));
assert.equal((html.match(/<th scope="col">Item /g)||[]).length,15);
assert.equal(ctx.WS12_REVIEW.groups.length,7);
ctx.WS12_REVIEW.groups.forEach(g=>g.students.forEach(s=>{
 assert.equal(ctx.CORE.ws[s].WS12.scoring,null,'No historical total is presented as current');
 assert.equal(ctx.CORE.ws[s].WS12.ocr.responses.length,15);
 assert.equal(ctx.CORE.ws[s].WS12.ocr.checks.length,15);
 assert(ctx.CORE.ws[s].WS12.ocr.checks.every(c=>!['structural_na','unknown','blank'].includes(c.flag)||c.correct===null));
}));
ctx.CORE.students.forEach(s=>Object.keys(ctx.CORE.ws[s]).filter(w=>w!=='WS12').forEach(w=>assert.equal(JSON.stringify(ctx.CORE.ws[s][w]),before[s+w],s+w+' unchanged')));
const index=fs.readFileSync(path.join(site,'index.html'),'utf8');
assert(index.indexOf('data/ws12_review.js')<index.indexOf('assets/ws12_review.js'));
assert(index.indexOf('assets/ws12_review.js')<index.indexOf('assets/worksheet_findings.js'));
assert(index.indexOf('assets/ws12_review.js')<index.indexOf('assets/app.js'));
const classes={};ctx.WS12_REVIEW.groups.forEach(g=>g.items.forEach(r=>classes[r.status]=(classes[r.status]||0)+g.students.length));
assert.equal(Object.values(classes).reduce((a,b)=>a+b,0),195);
console.log('PASS WS12 renderer,15 printed columns, status separation, no historical total leakage, non-WS12 records unchanged, script order.',classes);
